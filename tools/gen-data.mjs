// tools/gen-data.mjs
// Generates src/ui/ledger-data.ts and src/ui/exam-data.ts from data/ and exam/.
// No dependencies. Run with: node tools/gen-data.mjs

import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

// --- Load source files ---
const ledgerRaw = readFileSync(resolve(root, "data", "ledger.json"), "utf8");
const examRaw = readFileSync(resolve(root, "exam", "exam.json"), "utf8");

const ledger = JSON.parse(ledgerRaw);
const exam = JSON.parse(examRaw);

// --- Validate counts ---
if (ledger.length !== 48) {
  throw new Error(
    `Expected 48 ledger rows, got ${ledger.length}. Aborting.`
  );
}

const retrieval = exam.filter((item) => item.expectedStatus === "ANSWER");
if (retrieval.length !== 66) {
  throw new Error(
    `Expected 66 ANSWER exam items, got ${retrieval.length}. Aborting.`
  );
}

// --- Generate src/ui/ledger-data.ts ---
// Embed the raw JSON as a string constant so the UI parses it with parseLedger.
const ledgerEscaped = JSON.stringify(ledgerRaw);
const ledgerTs = `// AUTO-GENERATED by tools/gen-data.mjs — do not edit by hand.
export const LEDGER_JSON: string = ${ledgerEscaped};
`;
writeFileSync(resolve(root, "src", "ui", "ledger-data.ts"), ledgerTs, "utf8");
console.log("wrote src/ui/ledger-data.ts");

// --- Generate src/ui/exam-data.ts ---
const exam66 = retrieval.map((item) => ({
  id: item.id,
  question: item.question,
  expectedAnswer: item.expectedAnswer,
  expectedEvidence: item.expectedEvidence.map((e) => ({
    row: e.row,
    col: e.col,
  })),
}));

const examTs = `// AUTO-GENERATED by tools/gen-data.mjs — do not edit by hand.

export interface ExamItem {
  id: number;
  question: string;
  expectedAnswer: string;
  expectedEvidence: { row: number; col: string }[];
}

export const EXAM66: ExamItem[] = ${JSON.stringify(exam66, null, 2)};
`;
writeFileSync(resolve(root, "src", "ui", "exam-data.ts"), examTs, "utf8");
console.log("wrote src/ui/exam-data.ts");

console.log("gen-data: done (48 ledger rows, 66 retrieval questions).");
